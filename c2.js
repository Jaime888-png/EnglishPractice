var retryButton = document.getElementById("retryButton");
var choosePracticeButton = document.getElementById("choosePracticeButton");


practiceCards.forEach(function(card) {

    card.addEventListener("click", function() {

        practiceCards.forEach(function(item) {
            item.classList.remove("selected");
        });

        card.classList.add("selected");

        selectedCategory = card.getAttribute("data-category");

    });

});


lengthButtons.forEach(function(button) {

    button.addEventListener("click", function() {

        lengthButtons.forEach(function(item) {
            item.classList.remove("selected");
        });

        button.classList.add("selected");

        selectedLength = Number(button.getAttribute("data-length"));

    });

});


function shuffle(array) {

    var shuffled = array.slice();

    for (var i = shuffled.length - 1; i > 0; i--) {

        var j = Math.floor(Math.random() * (i + 1));

        var temp = shuffled[i];

        shuffled[i] = shuffled[j];

        shuffled[j] = temp;

    }

    return shuffled;
}


function startQuiz() {

    var filteredQuestions;

    if (selectedCategory === "Mixed Practice") {

        filteredQuestions = questions.slice();

    } else {

        filteredQuestions = questions.filter(function(question) {
            return question.category === selectedCategory;
        });

    }

    currentQuestions = shuffle(filteredQuestions).slice(0, selectedLength);

    currentQuestionIndex = 0;
    score = 0;

    document.querySelector(".practice-section").style.display = "none";
    document.querySelector(".quiz-length-section").style.display = "none";

    quizScreen.style.display = "block";
    resultsScreen.style.display = "none";

    showQuestion();

}


function showQuestion() {

    var currentQuestion = currentQuestions[currentQuestionIndex];

    questionNumber.textContent =
        "Question " + (currentQuestionIndex + 1) +
        " of " + currentQuestions.length;

    scoreDisplay.textContent =
        "Score: " + score;

    progressBar.style.width =
        ((currentQuestionIndex) / currentQuestions.length * 100) + "%";

    questionText.textContent = currentQuestion.question;

    answersContainer.innerHTML = "";

    feedback.innerHTML = "";
    feedback.className = "feedback";

    nextButton.style.display = "none";


    currentQuestion.answers.forEach(function(answer, index) {

        var button = document.createElement("button");

        button.className = "answer-button";

        button.textContent = answer;

        button.addEventListener("click", function() {

            checkAnswer(index);

        });

        answersContainer.appendChild(button);

    });

}


function checkAnswer(selectedAnswer) {

    var currentQuestion = currentQuestions[currentQuestionIndex];

    var answerButtons =
        answersContainer.querySelectorAll(".answer-button");


    answerButtons.forEach(function(button) {

        button.disabled = true;

    });


    if (selectedAnswer === currentQuestion.correct) {

        score++;

        feedback.className = "feedback correct";

        feedback.innerHTML =
            "<strong>Correct!</strong><br>" +
            currentQuestion.explanation;

    } else {

        feedback.className = "feedback incorrect";

        feedback.innerHTML =
            "<strong>Incorrect.</strong><br>" +
            "Correct answer: " +
            currentQuestion.answers[currentQuestion.correct] +
            "<br>" +
            currentQuestion.explanation;

    }


    scoreDisplay.textContent =
        "Score: " + score;

    nextButton.style.display = "block";

}


nextButton.addEventListener("click", function() {

    currentQuestionIndex++;

    if (currentQuestionIndex >= currentQuestions.length) {

        showResults();

    } else {

        showQuestion();

    }

});


function showResults() {

    quizScreen.style.display = "none";

    resultsScreen.style.display = "block";

    finalScore.textContent = score;

    totalQuestions.textContent =
        "/ " + currentQuestions.length;

    progressBar.style.width = "100%";


    var percentage =
        (score / currentQuestions.length) * 100;


    if (percentage >= 90) {

        resultMessage.textContent =
            "Outstanding! Your performance shows excellent command of advanced English.";

    } else if (percentage >= 70) {

        resultMessage.textContent =
            "Excellent work! You are handling challenging C2-level English very well.";

    } else if (percentage >= 50) {

        resultMessage.textContent =
            "Good effort! Keep practising advanced structures and vocabulary.";

    } else {

        resultMessage.textContent =
            "Keep practising! C2 English is demanding, so use the explanations to improve.";

    }

}



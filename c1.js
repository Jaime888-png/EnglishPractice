practiceCards.forEach(function(card) {

    card.addEventListener("click", function() {

        practiceCards.forEach(function(item) {
            item.classList.remove("selected");
        });

        card.classList.add("selected");

        selectedCategory =
            card.getAttribute("data-category");

    });

});


